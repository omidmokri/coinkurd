def _ar_years(n):
    """Arabic counted noun: سنتين / 3–10 سنوات / 11+ سنة"""
    return "سنتين" if n == 2 else ("سنة واحدة" if n == 1 else f"{n} سنوات" if 3 <= n <= 10 else f"{n} سنة")
FA_D = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")
AR_D = str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩")


def _digits(s, i):
    return s.translate(FA_D) if i == 0 else s.translate(AR_D) if i == 1 else s


def translate(title):
    """→ {"fa": …, "ckb": …, "ar": …} or None when the title is not fully understood"""
    t = " ".join(str(title or "").split())
    if not t:
        return None
    if t in IND:
        return dict(zip(L3, IND[t]))
    m = re.fullmatch(r"(?:([A-Z][a-z]+) )?(\d{1,2})-y (Bond|Note) Auction", t)          # "30-y Bond Auction", "German 30-y Bond Auction"
    if m and (not m.group(1) or m.group(1) in COUNTRY):
        return {lg: AUCTION[m.group(3)][i].format(n=_ar_years(int(m.group(2))) if i == 2 else _digits(m.group(2), i))
                + (" " + COUNTRY[m.group(1)][i] if m.group(1) else "") for i, lg in enumerate(L3)}
    m = re.fullmatch(r"(.+?) Speaks", t)
    if m:
        who_txt = m.group(1)
        head, _, tail = who_txt.partition(" ")
        if head in COUNTRY and tail:                     # "German Buba President Nagel": the bank already says where
            who_txt = tail
        org = None
        for k in sorted(ORG, key=len, reverse=True):
            if who_txt.startswith(k + " ") or who_txt == k:
                org = k
                break
        rest = who_txt[len(org):].strip() if org else who_txt
        role = None
        for k in sorted(ROLE, key=len, reverse=True):
            if rest.startswith(k + " "):
                role = k
                rest = rest[len(k):].strip()
                break
        if not rest or not re.fullmatch(r"[A-Z][A-Za-z'\-]+( [A-Za-z][A-Za-z'\-]+){0,2}", rest) or (not org and not role):
            return None
        out = {}
        for i, lg in enumerate(L3):
            who = " ".join(x for x in ((ROLE[role][i] if role else ""), (ORG[org][i] if org else "")) if x)
            out[lg] = f"{SPEECH[i]} {rest}" + (f" ({who})" if who else "")
        return out
    country = status = period = None
    words = t.split(" ")
    if words[0] in COUNTRY:
        country = words.pop(0)
    if words and words[0] in STATUS:
        status = words.pop(0)
    if words and words[-1] in PERIOD:
        period = words.pop()
    core = " ".join(words)
    if core not in IND:
        return None
    out = {}
    for i, lg in enumerate(L3):
        s = IND[core][i]
        if period:
            s += " " + PERIOD[period][i]
        if country:
            s += " " + COUNTRY[country][i]
        if status:
            s += f" ({STATUS[status][i]})"
        out[lg] = s
    return out


